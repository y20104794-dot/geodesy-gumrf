# ================= 2. ФУНКЦИИ ГЕНЕРАЦИИ БИЛЕТОВ СДО ГУМРФ =================
def fmt_dm(total_min):
    sign = "-" if total_min < 0 else ""
    am = abs(total_min)
    deg = int(am // 60)
    m = am % 60
    m_str = f"{int(m):02d}" if float(m).is_integer() else f"{m:04.1f}"
    return f"{sign}{deg}°{m_str}'"

